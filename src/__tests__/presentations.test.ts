import { describe, it, expect } from "vitest";
import { db } from "@/lib/db";
import fs from "fs";
import path from "path";

describe("Presentation Template Library & Logic", () => {
  it("should have at least 3 seeded presentation templates in SQLite", async () => {
    const templates = await db.template.findMany({
      where: { type: "PRESENTATION" },
    });
    expect(templates.length).toBeGreaterThanOrEqual(3);
  });

  it("each presentation template must have valid slide preview metadata", async () => {
    const templates = await db.template.findMany({
      where: { type: "PRESENTATION" },
    });

    for (const tmpl of templates) {
      expect(tmpl.slides).toBeDefined();
      const parsedSlides = JSON.parse(tmpl.slides!);
      expect(Array.isArray(parsedSlides)).toBe(true);
      expect(parsedSlides.length).toBeGreaterThanOrEqual(3);

      for (const slide of parsedSlides) {
        expect(slide.slideNumber).toBeDefined();
        expect(slide.title).toBeDefined();
        expect(slide.summary).toBeDefined();
      }
    }
  });

  it("should filter presentation templates by category", async () => {
    const startupTemplates = await db.template.findMany({
      where: {
        type: "PRESENTATION",
        category: "Startup & Investment",
      },
    });

    expect(startupTemplates.length).toBeGreaterThan(0);
    expect(startupTemplates.every((t: { category: string }) => t.category === "Startup & Investment")).toBe(true);
  });

  it("should search presentation templates by name or keyword", async () => {
    const results = await db.template.findMany({
      where: {
        type: "PRESENTATION",
        OR: [
          { name: { contains: "Pitch" } },
          { description: { contains: "Pitch" } },
        ],
      },
    });

    expect(results.length).toBeGreaterThan(0);
    expect(results[0].name).toContain("Pitch");
  });

  it("querying a non-existent presentation ID returns null / 404", async () => {
    const nonExistent = await db.template.findFirst({
      where: {
        id: "non-existent-pres-9999",
        type: "PRESENTATION",
      },
    });
    expect(nonExistent).toBeNull();
  });
});

describe("Presentation Physical Files, Integrity & Immutability", () => {
  it("all presentation templates must point to genuine, non-empty PPTX files on disk", async () => {
    const templates = await db.template.findMany({
      where: { type: "PRESENTATION" },
    });

    for (const tmpl of templates) {
      expect(tmpl.filePath).toBeDefined();
      const absolutePath = path.resolve(process.cwd(), tmpl.filePath!);

      expect(fs.existsSync(absolutePath)).toBe(true);
      const stats = fs.statSync(absolutePath);
      // Valid PPTX decks generated by pptxgenjs are > 20KB
      expect(stats.size).toBeGreaterThan(20000);

      // Verify OpenXML Zip container signature (PK\x03\x04)
      const buffer = fs.readFileSync(absolutePath);
      expect(buffer[0]).toBe(0x50); // 'P'
      expect(buffer[1]).toBe(0x4b); // 'K'
      expect(buffer[2]).toBe(0x03);
      expect(buffer[3]).toBe(0x04);
    }
  });

  it("creating a presentation draft or downloading leaves the master template and file strictly unchanged", async () => {
    const template = await db.template.findFirst({
      where: { type: "PRESENTATION" },
    });
    expect(template).not.toBeNull();

    const filePath = path.resolve(process.cwd(), template!.filePath!);
    const beforeStats = fs.statSync(filePath);
    const beforeContent = template!.content;

    // Create a new independent draft
    const draft = await db.draft.create({
      data: {
        templateId: template!.id,
        type: "PRESENTATION",
        title: `${template!.name} (Downloaded Presentation Copy)`,
        content: template!.content,
        slides: template!.slides,
      },
    });

    expect(draft.id).toBeDefined();
    expect(draft.id).not.toBe(template!.id);

    // Verify template record in SQLite is untouched
    const freshTemplate = await db.template.findUnique({
      where: { id: template!.id },
    });
    expect(freshTemplate!.content).toBe(beforeContent);
    expect(freshTemplate!.updatedAt.getTime()).toBe(template!.updatedAt.getTime());

    // Verify physical PPTX master file on disk was not modified or overwritten
    const afterStats = fs.statSync(filePath);
    expect(afterStats.size).toBe(beforeStats.size);
    expect(afterStats.mtimeMs).toBe(beforeStats.mtimeMs);
  });
});
